def get_profile_extra_agents(profile_name: str) -> set:
    if not profile_name:
        return set()
    profile_path = REPO_ROOT / ".github" / "profiles.yml"
    if not profile_path.exists():
        return set()
    try:
        import yaml
        with open(profile_path) as f:
            data = yaml.safe_load(f)
            return set(data.get("profiles", {}).get(profile_name, {}).get("extra_agents", []))
    except Exception:
        return set()

def should_include_agent(src: Path, profile_name: str, extra_agents: set) -> bool:
    if not profile_name:
        return True
    if src.stem in extra_agents:
        return True
    
    # Check frontmatter
    content = src.read_text()
    if not content.startswith("---"):
        return True # Universal if no frontmatter

    # Bound on a line-anchored "\n---" (matches parse_frontmatter()'s own
    # boundary logic), not a blind content.split("---", 2) — a bare substring
    # split breaks the moment the frontmatter body contains "---" anywhere
    # earlier, e.g. a YAML comment like "# --- Squad Leads --- " inside a
    # delegates_to list (real example: cto.md — this silently truncated the
    # parse right after `hierarchy:`, dropping the real `profile:` field and
    # making the agent look profile-universal regardless of what it declared).
    end = content.find("\n---", 3)
    if end == -1:
        return True
    fm_block = content[3:end]

    try:
        import yaml
        fm = yaml.safe_load(fm_block)
        agent_profiles = fm.get("profile", "")
        if not agent_profiles:
            return True # Universal
        
        allowed = [p.strip() for p in str(agent_profiles).split(",")]
        return profile_name in allowed
    except Exception:
        return True # Fallback to include


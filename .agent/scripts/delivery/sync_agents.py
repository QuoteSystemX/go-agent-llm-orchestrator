def sync_skills(target: str, dry_run: bool, check: bool):
    """Expose .agent/skills/<name>/ as native Claude Code / OpenCode skills.

    Claude Code only scans .claude/skills/<name>/SKILL.md (see
    https://code.claude.com/docs/en/skills) and OpenCode only scans
    .opencode/skills/<name>/SKILL.md project-locally (see
    https://opencode.ai/docs/skills/) — .agent/skills/ was never on either
    path, so none of these 160+ knowledge modules were ever real native
    skills for either tool; agents just self-instruct to Read them.

    (OpenCode also auto-discovers .claude/skills/ with no extra config, so
    skills were already reachable there indirectly — this makes it explicit
    and matches the .opencode/agents/ + .opencode/commands/ symmetry with
    .claude/, instead of relying on that implicit cross-tool fallback.)

    Symlinks the whole skill directory rather than copying SKILL.md alone:
    many skills ship supporting files (references/, scripts/, examples/,
    sdks/) that SKILL.md links to with paths relative to its own directory
    (e.g. clickhouse-best-practices/SKILL.md -> references/schema-design.md).
    A symlinked directory keeps those resolving correctly and needs no
    regeneration when skill content changes — unlike agents/commands, which
    are rendered text and must be rewritten by _write() on every edit.
    """
    config = TARGETS.get(target, {})
    skills_out = config.get("skills_out")
    if skills_out is None:
        return  # target has no native skills directory

    skills_out.mkdir(parents=True, exist_ok=True)
    expected_links = set()

    for skill_dir in sorted(p for p in SKILLS_SRC.iterdir() if p.is_dir()):
        if skill_dir.name in SKILL_SKIP_DIRS or not (skill_dir / "SKILL.md").exists():
            continue

        link_path = skills_out / skill_dir.name
        expected_links.add(link_path)
        rel_target = Path(os.path.relpath(skill_dir, skills_out))
        rel_display = link_path.relative_to(TARGET_ROOT)

        if dry_run:
            print(f"  [DRY] {rel_display} -> {rel_target}")
            continue

        if check:
            if not link_path.is_symlink() or Path(os.readlink(link_path)) != rel_target:
                print(f"  [DRIFT] {rel_display}")
                sys.exit(1)
            continue

        if link_path.is_symlink():
            if Path(os.readlink(link_path)) == rel_target:
                print(f"  ✓ {rel_display}")
                continue
            link_path.unlink()
        elif link_path.exists():
            # A real file/directory sits where a symlink belongs — don't
            # clobber something that might be hand-authored; report and skip.
            print(f"  ⚠️  {rel_display} exists and is not a symlink — skipping (remove it manually to let sync manage it)")
            continue

        link_path.symlink_to(rel_target, target_is_directory=True)
        print(f"  🔗 {rel_display} -> {rel_target}")

    # Orphan cleanup: a managed symlink whose source skill no longer exists.
    # Only ever removes symlinks this function itself would create — never a
    # real directory, matching the skip-and-warn behavior above.
    if not check and skills_out.exists():
        for item in sorted(skills_out.iterdir()):
            if item in expected_links or not item.is_symlink():
                continue
            rel = item.relative_to(TARGET_ROOT)
            if dry_run:
                print(f"  [ORPHAN-DRY] {rel}")
            else:
                item.unlink()
                print(f"  🗑️  {rel}")


def _build_provider_section() -> dict:
    """Build opencode provider config pointing to the MCP LLM Broker HTTP API.

    Only tier-level aliases (auto, L1-L4) are registered as models.
    The MCP LLM Broker resolves each alias to a concrete model at runtime
    using router_rules.json — keeping opencode.json fully provider-agnostic.
    """
    port = 11436
    mcp_broker_port = os.environ.get("MCP_BROKER_HTTP_PORT", str(port))

    # Only expose tier aliases — broker resolves to real models via router_rules.json
    models = {alias: {} for alias in ["auto", "L1", "L2", "L3", "L4"]}

    return {
        "mcp-llm-broker": {
            "name": "MCP LLM Broker",
            "npm": "@ai-sdk/openai-compatible",
            "options": {
                "baseURL": f"http://localhost:{mcp_broker_port}/v1",
            },
            "models": models,
        },
    }


